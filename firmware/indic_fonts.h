// Custom U8g2 bitmap fonts for the languages this project's dropdown
// offers that have NO glyph coverage anywhere in U8g2's own built-in
// font set (Tamil, Telugu, Gujarati, Punjabi/Gurmukhi), plus better-
// quality replacements for the three U8g2 DOES ship (Devanagari,
// Malayalam) via its generic "Unifont" font - Unifont's Indic coverage
// is thin/rough since it prioritizes broad Unicode coverage over any
// one script's typographic quality. All seven below are instead built
// from Google's actual Noto Sans <Script> typefaces (SIL Open Font
// License), which is what browsers/phones use for these scripts too -
// real letterforms, not a generic fallback.
//
// Generation pipeline (reproducible, not hand-edited):
//   1. Downloaded the variable-weight Noto Sans <Script> TTF from
//      Google's own font repository (github.com/google/fonts).
//   2. Instanced it to the static Regular (wght=400) weight with
//      fonttools' varLib.instancer.
//   3. Rasterized the outlines to a 16px BDF bitmap font with otf2bdf.
//   4. Converted that BDF to this U8g2 C font format with u8g2's own
//      official bdfconv tool (github.com/olikraus/u8g2, tools/font/
//      bdfconv), built from source with the repo's own Makefile.
// Each font includes ASCII 0x20-0x7E (so the "[OFFERING] Name: ..."
// wrapper text and any Latin punctuation in a blessing still draws
// correctly) plus that script's core Unicode block.
//
// IMPORTANT LIMITATION, not fixed by better glyphs: U8g2 has no text
// shaping engine. It draws one glyph per Unicode codepoint, strictly in
// the order the bytes appear - it does NOT reorder a vowel sign that
// visually belongs before its consonant, and does NOT fuse consonant
// conjuncts into their combined ligature form, the way a phone or
// browser (which has a real shaping engine - HarfBuzz or similar) does.
// Devanagari, Tamil, Telugu, Gujarati, Gurmukhi, Malayalam, and Bengali
// all rely on exactly that kind of reordering/fusing for correctly
// typeset text. Every individual character will be recognizable and
// legible - the SAME script/font-quality problem does not remain - but
// multi-character clusters (which are common, not rare, in all these
// scripts) will visually differ from how the same text renders on the
// dashboard or a phone. Implementing real shaping is a much larger
// undertaking (essentially building a small HarfBuzz-equivalent for the
// ESP32) and is out of scope here.

